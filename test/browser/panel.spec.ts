const developmentId = 'connection-11111111-1111-4111-a111-111111111111'
const rowFor = (page: Page, name: string) => page.locator('.dc-list > li').filter({ has: page.getByText(name, { exact: true }) })
async function openWithPausedClock(page: Page, url: string) {
  await page.clock.install({ time: new Date('2026-01-01T00:00:00Z') })
  await page.clock.pauseAt(new Date('2026-01-01T00:00:00Z'))
  await page.goto(url)
}
async function addDialog(page: Page) {
  await page.getByRole('button', { name: en.add, exact: true }).click()
  return page.locator('dialog.dc-dialog')
}
async function manual(page: Page) {
  const dialog = await addDialog(page)
  await dialog.getByRole('button', { name: en.addManually, exact: true }).click()
  return dialog
}
async function menu(page: Page, name: string, action: string) {
  await page.getByRole('button', { name: en.actions + ': ' + name, exact: true }).click()
  await page.getByRole('menuitem', { name: action, exact: true }).click()
}
async function data(page: Page, key: string) { return JSON.parse(await page.locator('html').getAttribute('data-' + key) ?? '{}') }

test('selecting multiple discovered hosts saves distinct rows and immediately connects without waiting for SSH', async ({ page }) => {
  await openWithPausedClock(page, '/?populated&slow')
  const dialog = await addDialog(page)
  await expect(dialog.getByRole('checkbox', { name: 'Dev', exact: true })).toHaveCount(0)
  await dialog.getByRole('checkbox', { name: 'DH_H800', exact: true }).check()
  await dialog.getByRole('checkbox', { name: 'WSL_Ubuntu_R', exact: true }).check()
  await dialog.getByRole('button', { name: en.addSelected + ' (2)', exact: true }).click()
  await expect(dialog).toHaveCount(0)
  await expect(page.locator('.dc-list > li')).toHaveCount(4)
  for (const host of ['DH_H800', 'WSL_Ubuntu_R']) {
    await expect(rowFor(page, host).getByRole('switch')).toBeChecked()
    await expect(rowFor(page, host).getByRole('status')).toHaveText(en.connecting)
  }
  expect(await data(page, 'connects')).toEqual({ DH_H800: 1, WSL_Ubuntu_R: 1 })
  expect(new Set((await data(page, 'records')).map((row: { id: string }) => row.id)).size).toBe(4)
  await page.clock.runFor(3000)
  await expect(rowFor(page, 'DH_H800').getByRole('status')).toHaveText(en.connected)
})

