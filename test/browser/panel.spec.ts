test('the native add dialog contains focus and Escape returns to its trigger', async ({ page }) => {
  await page.goto('/?populated&parentEscape')
  const dialog = await addDialog(page)
  await expect(dialog).toBeVisible()
  await expect.poll(() => dialog.evaluate(element => element.contains(document.activeElement))).toBe(true)
  for (let count = 0; count < 10; count++) {
    await page.keyboard.press('Tab')
    // The browser may focus its chrome between tab cycles (activeElement=body),
    // but the native modal must never move focus to background page controls.
    expect(await dialog.evaluate(element => document.activeElement === document.body || element.contains(document.activeElement))).toBe(true)
  }
  await page.keyboard.press('Escape')
  await expect(dialog).toHaveCount(0)
  await expect(page.getByRole('button', { name: en.add, exact: true })).toBeFocused()
  await expect(page.locator('html')).toHaveAttribute('data-parent-escapes', '0')
  await page.keyboard.press('Escape')
  await expect(page.locator('html')).toHaveAttribute('data-parent-escapes', '1')
})

