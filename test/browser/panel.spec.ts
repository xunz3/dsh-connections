async function visibility(page: Page, state: 'hidden' | 'visible') {
  await page.evaluate(value => {
    Object.defineProperty(document, 'visibilityState', { configurable: true, value })
    document.dispatchEvent(new Event('visibilitychange'))
  }, state)
}

test('connection polling pauses while hidden and resumes immediately without overlapping reads', async ({ page }) => {
  await openWithPausedClock(page, '/?populated&poll=slow')
  const before = Number(await page.locator('html').getAttribute('data-list-requests'))
  await visibility(page, 'hidden')
  await page.clock.runFor(10_000)
  await expect(page.locator('html')).toHaveAttribute('data-list-requests', String(before))
  await visibility(page, 'visible')
  await expect(page.locator('html')).toHaveAttribute('data-list-requests', String(before + 1))
  await visibility(page, 'hidden'); await visibility(page, 'visible')
  await expect(page.locator('html')).toHaveAttribute('data-active-lists', '1')
  await expect(page.locator('html')).toHaveAttribute('data-list-requests', String(before + 1))
  await page.clock.runFor(800)
  await expect(page.locator('html')).toHaveAttribute('data-list-requests', String(before + 2))
  await expect(page.locator('html')).toHaveAttribute('data-active-lists', '1')
})

